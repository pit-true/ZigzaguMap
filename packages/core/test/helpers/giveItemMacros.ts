/**
 * ND・Chronos の xse_commands.s と同じ形の、giveitem まわりのマクロ（合成）。
 * `copyvarifnotzero` は定義の無い `setorcopyvar` を呼ぶので、GIVE_ITEM_MACROS だけでは giveitem / obtainitem / finditem が組めない。
 * SETORCOPYVAR を足すと組める（中身は setvarifnotzero と同じ 0x1A）。
 */
export const GIVE_ITEM_MACROS = [
  ".equ MSG_OBTAIN, 0x0",
  ".equ MSG_FIND, 0x1",
  ".macro callstd function:req",
  ".byte 0x09",
  ".byte \\function",
  ".endm",
  ".macro if condition:req goto_or_call:req script:req",
  ".byte \\goto_or_call, \\condition",
  ".word \\script",
  ".endm",
  ".macro copyvar destination:req, source:req",
  ".byte 0x19",
  ".2byte \\destination",
  ".2byte \\source",
  ".endm",
  ".macro setvarifnotzero destination:req, source:req",
  ".byte 0x1a",
  ".2byte \\destination",
  ".2byte \\source",
  ".endm",
  ".macro copyvarifnotzero destination:req, source:req",
  "\tsetorcopyvar \\destination, \\source",
  ".endm",
  ".macro cmpvar var:req, value:req",
  ".byte 0x21",
  ".2byte \\var",
  ".2byte \\value",
  ".endm",
  ".macro compare var:req, value:req",
  "\tcmpvar \\var, \\value",
  ".endm",
  ".macro switch var:req",
  "\tcopyvar 0x8000, \\var",
  ".endm",
  ".macro case condition:req, dest:req",
  "\tcompare 0x8000, \\condition",
  "\tif equal _goto \\dest",
  ".endm",
  ".macro giveitem item:req amount:req msgtype:req",
  "\tcopyvarifnotzero 0x8000 \\item",
  "\tcopyvarifnotzero 0x8001 \\amount",
  "\tcallstd \\msgtype",
  ".endm",
  ".macro finditem item:req amount:req",
  "\tgiveitem \\item, \\amount, MSG_FIND",
  ".endm",
  ".macro obtainitem item:req amount:req",
  "\tgiveitem \\item, \\amount, MSG_OBTAIN",
  ".endm",
  "",
].join("\n");

/** 欠けている setorcopyvar の定義（setvarifnotzero と同じ命令）。 */
export const SETORCOPYVAR = [".macro setorcopyvar destination:req, source:req", "\tsetvarifnotzero \\destination, \\source", ".endm", ""].join("\n");
