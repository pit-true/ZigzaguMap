/** 00〜FF の 256 件（名前の無い値は 16 進 2 桁だけ）。 */
function comboItems(names: Readonly<Record<number, string>>): string[] {
  return Array.from({ length: 256 }, (_, i) => names[i] ?? hex(i, 2));
}

