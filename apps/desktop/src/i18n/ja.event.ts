/** ステータスバーの座標（範囲内は 2 桁、0x100 以上は 8 桁。AdvanceMap と同じ）。 */
function hexCoord(v: number): string {
  return v > 0xff ? hex(v >>> 0, 8) : hex(v, 2);
}
